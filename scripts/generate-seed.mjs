// Generates supabase/migrations/003_seed_content.sql from the EXISTING static mission files,
// so nothing the learner app has today is lost. Run:  node scripts/generate-seed.mjs
// It also checks that every mission has BOTH Hausa and English text (same rule the database enforces).
import { writeFileSync } from 'node:fs'
import { missions, badges } from '../src/data/missions.js'
import { cassavaMission } from '../src/data/cassavaMission.js'
import { potatoMission } from '../src/data/potatoMission.js'
import { wasteMission } from '../src/data/wasteMission.js'
import { compostMission } from '../src/data/compostMission.js'
import { solarMission } from '../src/data/solarMission.js'
import { robotMission } from '../src/data/robotMission.js'
import { deviceMission } from '../src/data/deviceMission.js'

const content = { cassava: cassavaMission, potato: potatoMission, waste: wasteMission, compost: compostMission, solar: solarMission, robot: robotMission, device: deviceMission }
const categories = [
  { slug: 'food-agriculture', pos: 1, name: { ha: 'Abinci da Noma', en: 'Food and Farming' } },
  { slug: 'environment',      pos: 2, name: { ha: 'Muhalli da Sake Amfani', en: 'Environment and Reuse' } },
  { slug: 'energy',           pos: 3, name: { ha: 'Makamashi', en: 'Energy' } },
  { slug: 'engineering',      pos: 4, name: { ha: 'Ginawa da Ƙirƙira', en: 'Building and Inventing' } },
]
const categoryOf = { cassava: 'food-agriculture', potato: 'food-agriculture', waste: 'environment', compost: 'environment', solar: 'energy', robot: 'engineering', device: 'engineering' }

const q = (s) => "'" + String(s).replaceAll("'", "''") + "'"
const j = (o) => '$j$' + JSON.stringify(o) + '$j$::jsonb'

// Same rule as public.jsonb_lang_gaps(): any {ha,en} object needs both non-empty.
const gaps = (v, path = '') => {
  if (Array.isArray(v)) return v.flatMap((x, i) => gaps(x, `${path}[${i}]`))
  if (v && typeof v === 'object') {
    if ('ha' in v || 'en' in v) return ['ha', 'en'].filter((l) => !String(v[l] ?? '').trim()).map((l) => `${path}.${l}`)
    return Object.entries(v).flatMap(([k, x]) => gaps(x, `${path}.${k}`))
  }
  return []
}

// SQL lines that insert one mission's steps and questions (uses a plpgsql variable v_id).
const contentInserts = (c) => {
  const lines = []
  const step = (stage, type, key, pos, body) =>
    lines.push(`  insert into public.mission_steps (mission_id, stage, step_type, step_key, position, content) values (v_id, ${q(stage)}, ${q(type)}, ${key ? q(key) : 'null'}, ${pos}, ${j(body)});`)
  c.teach.forEach((p, i) => step('teach', i === 0 ? 'story' : 'explanation', null, i, p))
  Object.entries(c.steps).forEach(([k, s], i) => step('demo', 'demonstration', k, i, s))
  c.procedures.forEach((p, i) => step('procedure', 'demonstration', p.id, i, p))
  c.challenges.forEach((ch, i) => step('challenge', ch.type === 'business' ? 'challenge' : 'drag_drop', ch.key, i, ch))
  c.quiz.forEach((qq, i) =>
    lines.push(`  insert into public.game_questions (mission_id, position, question, options, correct_index, explanation, points) values (v_id, ${i}, ${j(qq.q)}, ${j(qq.a)}, ${qq.c}, ${j(qq.e)}, ${Number(c.rewards.quiz) || 5});`))
  return lines
}

const problems = []
const out = []
out.push('-- GENERATED by scripts/generate-seed.mjs from src/data/*.js — do not edit by hand.')
out.push('-- Safe to re-run: each block skips itself if its mission already exists.\n')

out.push('insert into public.categories (slug, name, position) values')
out.push(categories.map((c) => `  (${q(c.slug)}, ${j(c.name)}, ${c.pos})`).join(',\n'))
out.push('on conflict (slug) do nothing;\n')

// Badge conditions are descriptive: which mission events grant each badge.
const badgeEvents = {}
for (const [slug, m] of Object.entries(content))
  for (const [ev, spec] of Object.entries(m.rewards))
    if (Array.isArray(spec) && spec[1]) (badgeEvents[spec[1]] ||= []).push({ mission: slug, event: ev })
out.push('insert into public.rewards (slug, emoji, name, how, points, condition) values')
out.push(badges.map((b) => `  (${q(b.id)}, '🏅', ${j(b.name)}, ${j(b.how)}, 0, ${j({ granted_by: badgeEvents[b.id] ?? [] })})`).join(',\n'))
out.push('on conflict (slug) do nothing;\n')

// Locked placeholders (missions 04–07): visible as "coming soon", not playable.
for (const m of missions.filter((x) => !content[x.id])) {
  out.push(`insert into public.missions (slug, mission_no, emoji, title, status, category_id)
select ${q(m.id)}, ${m.no}, ${q(m.emoji)}, ${j(m.title)}, 'coming_soon', (select id from public.categories where slug = ${q(categoryOf[m.id])})
where not exists (select 1 from public.missions where slug = ${q(m.id)});\n`)
}

for (const m of missions.filter((x) => content[x.id])) {
  const c = content[m.id]
  const bad = gaps([m.title, c.title, c.teach, c.steps, c.procedures, c.challenges, c.quiz], m.id)
  if (bad.length) problems.push(...bad)
  const engineOptions = { header_title: c.title, ...(c.mixed ? { mixed: true } : {}) }
  out.push(`do $seed$
declare v_id uuid; v_status text;
begin
  select id, status into v_id, v_status from public.missions where slug = ${q(m.id)};
  if v_id is not null and v_status <> 'coming_soon' then
    raise notice 'mission ${m.id} already seeded - skipping';
    return;
  end if;
  if v_id is null then
    insert into public.missions (slug, mission_no, emoji, title, category_id, stages, reward_rules, engine_options, status)
    values (${q(m.id)}, ${m.no}, ${q(m.emoji)}, ${j(m.title)},
            (select id from public.categories where slug = ${q(categoryOf[m.id])}),
            ${j(c.stages)}, ${j(c.rewards)}, ${j(engineOptions)}, 'draft')
    returning id into v_id;
  else  -- was a "coming soon" placeholder: fill it in
    update public.missions set stages = ${j(c.stages)}, reward_rules = ${j(c.rewards)},
           engine_options = ${j(engineOptions)}, status = 'draft' where id = v_id;
  end if;`)
  out.push(...contentInserts(c))
  out.push(`  -- publishing runs the Hausa+English completeness trigger; the seed fails loudly if anything is missing
  update public.missions set status = 'published' where id = v_id;
end $seed$;\n`)
}

out.push(`-- ---- branding & language settings (editable later in the admin panel) ----
insert into public.app_settings (key, value) values
  ('app_name',            '"ASARTUN TECH BUILDER"'::jsonb),
  ('parent_company',      '"ASARTUN STORE LIMITED"'::jsonb),
  ('tagline',             ${j({ ha: '', en: '' })}),
  ('logo_path',           'null'::jsonb),
  ('support',             '{"email":"","phone":"","website":""}'::jsonb),
  ('default_language',    '"ha"'::jsonb),
  ('available_languages', '["ha","en"]'::jsonb)
on conflict (key) do nothing;`)

// Pull the real tagline from the existing UI dictionary (text match: that file has extension-less imports Node cannot load).
import { readFileSync } from 'node:fs'
const dict = readFileSync(new URL('../src/data/translations.js', import.meta.url), 'utf8')
const tags = [...dict.matchAll(/tagline:\s*'([^']*)'/g)].map((x) => x[1])   // first = ha, second = en
if (tags.length >= 2) out[out.length - 1] = out[out.length - 1].replace(j({ ha: '', en: '' }), j({ ha: tags[0], en: tags[1] }))

// 004: bring an ALREADY-SEEDED database up to date with edited mission content (idempotent).
// Replaces the steps and questions of the listed missions; learners' saved progress is not touched.
const refreshSlugs = ['waste']
const ref = ['-- GENERATED by scripts/generate-seed.mjs — refreshes lesson content of missions edited after the first seed.',
  '-- Safe to run more than once. Run it only if you already ran 003 before the content was extended.\n']
for (const slug of refreshSlugs) {
  ref.push(`do $r$
declare v_id uuid;
begin
  select id into v_id from public.missions where slug = ${q(slug)};
  if v_id is null then raise exception 'mission ${slug} not found - run 003 first'; end if;
  delete from public.mission_steps  where mission_id = v_id;
  delete from public.game_questions where mission_id = v_id;`)
  ref.push(...contentInserts(content[slug]))
  ref.push(`  -- re-validates the whole mission (Hausa + English) if it is published
  update public.missions set updated_at = now() where id = v_id;
end $r$;\n`)
}
writeFileSync(new URL('../supabase/migrations/004_refresh_mission_content.sql', import.meta.url), ref.join('\n') + '\n')

if (problems.length) {
  console.error('MISSING TRANSLATIONS in existing content:\n' + problems.join('\n'))
  process.exitCode = 1
}
writeFileSync(new URL('../supabase/migrations/003_seed_content.sql', import.meta.url), out.join('\n') + '\n')
console.log(`Wrote 003_seed_content.sql — ${Object.keys(content).length} missions, ${missions.length - Object.keys(content).length} placeholders, ${badges.length} badges. Translation gaps: ${problems.length}`)
