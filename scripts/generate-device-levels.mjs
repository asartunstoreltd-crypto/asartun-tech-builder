// Generates supabase/migrations/014_device_levels_draft.sql: adds the Level 1 and Level 3 Home Device lessons as DRAFTS
// (an admin reviews, edits and publishes them), and puts the existing Level 2 'device' mission in the same family.
// Run:  node scripts/generate-device-levels.mjs
import { writeFileSync } from 'node:fs'
import { deviceL1 } from '../src/data/deviceL1Mission.js'
import { deviceL3 } from '../src/data/deviceL3Mission.js'

const q = (s) => "'" + String(s).replaceAll("'", "''") + "'"
const j = (o) => '$j$' + JSON.stringify(o) + '$j$::jsonb'
const FAMILY = 'home-device'

const inserts = (c) => {
  const out = []
  const step = (stage, type, key, pos, body) =>
    out.push(`  insert into public.mission_steps (mission_id, stage, step_type, step_key, position, content) values (v_id, ${q(stage)}, ${q(type)}, ${key ? q(key) : 'null'}, ${pos}, ${j(body)});`)
  c.teach.forEach((p, i) => step('teach', i === 0 ? 'story' : 'explanation', null, i, p))
  Object.entries(c.steps).forEach(([k, s], i) => step('demo', 'demonstration', k, i, s))
  c.procedures.forEach((p, i) => step('procedure', 'demonstration', p.id, i, p))
  c.challenges.forEach((ch, i) => step('challenge', ch.type === 'business' ? 'challenge' : 'drag_drop', ch.key, i, ch))
  c.quiz.forEach((qq, i) => out.push(`  insert into public.game_questions (mission_id, position, question, options, correct_index, explanation, points) values (v_id, ${i}, ${j(qq.q)}, ${j(qq.a)}, ${qq.c}, ${j(qq.e)}, ${Number(c.rewards.quiz) || 5});`))
  return out
}

const block = (c, slug, emoji, level) => [
  `do $d$
declare v_id uuid;
begin
  if exists (select 1 from public.missions where slug = ${q(slug)}) then
    raise notice 'mission ${slug} already exists - skipping';
    return;
  end if;
  insert into public.missions (slug, mission_no, emoji, title, description, category_id, difficulty, status, stages, reward_rules, engine_options, objectives, access, level_id, risk_level, family)
  values (${q(slug)}, (select coalesce(max(mission_no), 0) + 1 from public.missions), ${q(emoji)}, ${j(c.title)}, ${j(c.description)},
          (select id from public.categories where slug = 'engineering'), ${q(level === 'level-1' ? 'beginner' : 'advanced')}, 'draft',
          ${j(c.stages)}, ${j(c.rewards)}, ${j({ header_title: c.title, mixed: true })}, ${j(c.objectives)},
          coalesce((select access from public.missions where slug = 'device'), 'free'),
          (select id from public.lesson_levels where slug = ${q(level)}), 'medium', ${q(FAMILY)})
  returning id into v_id;`,
  ...inserts(c),
  `end $d$;\n`].join('\n')

const sql = [
  '-- GENERATED by scripts/generate-device-levels.mjs from src/data/deviceL1Mission.js and deviceL3Mission.js. Do not edit by hand.',
  '-- Adds Home Device Level 1 and Level 3 as DRAFTS (not visible to learners) and groups all three levels in family \'home-device\'.',
  '-- Needs 001-006, 010, 011 and 013. Safe to run twice (a lesson that already exists is skipped).',
  '-- Science and Hausa text are first drafts: an admin must review them (Admin -> Missions) before pressing Publish.',
  '-- The existing Level 2 lesson (slug device) is not changed except for getting the family name.\n',
  "update public.missions set family = 'home-device' where slug = 'device' and family is null;\n",
  block(deviceL1, 'device-l1', '🏺', 'level-1'),
  block(deviceL3, 'device-l3', '🧭', 'level-3'),
].join('\n')
writeFileSync(new URL('../supabase/migrations/014_device_levels_draft.sql', import.meta.url), sql + '\n')
console.log('Wrote 014_device_levels_draft.sql', sql.length, 'characters')
